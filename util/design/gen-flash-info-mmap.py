r"""Generate flash info C header from memory map definition file (hjson).
"""
import argparse
import logging as log
import sys
from pathlib import Path
from typing import Dict

from lib.common import wrapped_docstring
from lib.FlashInfoMemMap import FlashInfoMemMap
from mako import exceptions
from mako.template import Template

# This makes topgen libraries available to template files.
sys.path.append(Path(__file__).parents[1])

TPL_GEN_COMMENT = '''// DO NOT EDIT THIS FILE DIRECTLY.
// It has been generated with ./util/design/gen-flash-info-mmap.py
'''


def render_template(template_path: Path, target_path: Path,
                    params: Dict[str, object]):
    try:
        tpl = Template(filename=str(template_path))
    except OSError as e:
        log.error(f"Error creating template: {e}")
        exit(1)

    try:
        expansion = tpl.render(**params)
    except exceptions.MakoException:
        log.error(exceptions.text_error_template().render())
        exit(1)

    try:
        with target_path.open(mode='w', encoding='UTF-8') as outfile:
            outfile.write(expansion)
    except OSError as e:
        log.error(f"Error rendering template: {e}")
        exit(1)


def main():
    log.basicConfig(level=log.WARNING, format="%(levelname)s: %(message)s")

    parser = argparse.ArgumentParser(
        prog="gen-flash-info-mmap",
        description=wrapped_docstring(),
        formatter_class=argparse.RawDescriptionHelpFormatter)

    # Generator options for compile time random netlist constants
    parser.add_argument('--gen-keys',
                        action='store_true',
                        help='Recompute random constants with topgen seed')

    parser.add_argument('--template',
                        required=True,
                        type=Path,
                        metavar='<path>',
                        help='Path to the header template to generate from.')
    parser.add_argument('--mmap',
                        required=True,
                        type=Path,
                        metavar='<path>',
                        help='Path to the Flash Info memory map.')
    parser.add_argument('--output',
                        required=True,
                        type=Path,
                        metavar='<path>',
                        help='Path to write the generated C/C++ header.')
    args = parser.parse_args()

    mmap = FlashInfoMemMap.from_mmap_path(
        args.mmap,
        args.gen_keys,
    )
    # render template
    params = {
        "flash_info_mmap": mmap,
        "gen_comment": TPL_GEN_COMMENT,
    }
    render_template(args.template, args.output, params)


if __name__ == "__main__":
    main()
