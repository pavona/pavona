/**
 * Test for check_sk, the FIPS 203 Section 7.3 hash check on the ML-KEM
 * decapsulation key. check_sk takes the encapsulation key (ek) directly
 * (pointer + length), since the caller already knows where ek lives within
 * the decapsulation key for both the masked and unmasked key layouts; the
 * stored hash H(ek) is expected to immediately follow ek.
 *
 * Exercises a real ek/H(ek) pair from an ML-KEM-1024 keypair (must pass).
 * Tests 2 and 3 copy it to a scratch buffer and corrupt one word (of the
 * stored hash, then of ek) to check that both are rejected. The number of
 * incorrect results is accumulated in w0, which must be zero on success.
 *
 * valid_ek is the encapsulation key from an ML-KEM-1024 keypair generated
 * with kyber_py.ml_kem.ML_KEM_1024._keygen_internal(d, z), where d and z are
 * the first two 32-byte draws of Python's `random` module seeded with 0,
 * followed by its real SHA3-256 hash.
 */

/* Hardened boolean values. Should match the values in `hardened_asm.h`. */
.equ HARDENED_BOOL_TRUE, 0x739
.equ HARDENED_BOOL_FALSE, 0x1d4

.section .text.start

main:
  bn.xor w31, w31, w31   /* all-zero register */
  bn.xor w3, w3, w3      /* w3 = failure counter (check_sk clobbers w0, w8) */

  /* Test 1: a valid ek/H(ek) pair (stored hash == H(ek)) must return TRUE. */
  la   x10, valid_ek
  li   x11, 1568
  jal  x1, check_sk
  addi x5, x0, HARDENED_BOOL_TRUE
  beq  x10, x5, _t1_ok
  bn.addi w3, w3, 1
_t1_ok:

  /* Test 2: a corrupted stored hash must return FALSE. Corrupt a fresh copy
   * of valid_ek so the original is left intact for test 3. */
  la   x6, valid_ek
  la   x7, scratch_ek
  li   x28, 50   /* 1600 bytes / 32 bytes per chunk */
  loop x28, 2
    bn.lid x0, 0(x6++)
    bn.sid x0, 0(x7++)
  la   x6, scratch_ek
  lw   x29, 1568(x6)   /* first word of the stored hash */
  xori x29, x29, -1
  sw   x29, 1568(x6)
  la   x10, scratch_ek
  li   x11, 1568
  jal  x1, check_sk
  addi x5, x0, HARDENED_BOOL_FALSE
  beq  x10, x5, _t2_ok
  bn.addi w3, w3, 1
_t2_ok:

  /* Test 3: a corrupted encapsulation key must return FALSE. */
  la   x6, valid_ek
  la   x7, scratch_ek
  li   x28, 50
  loop x28, 2
    bn.lid x0, 0(x6++)
    bn.sid x0, 0(x7++)
  la   x6, scratch_ek
  lw   x29, 1564(x6)   /* last word of ek */
  xori x29, x29, -1
  sw   x29, 1564(x6)
  la   x10, scratch_ek
  li   x11, 1568
  jal  x1, check_sk
  addi x5, x0, HARDENED_BOOL_FALSE
  beq  x10, x5, _t3_ok
  bn.addi w3, w3, 1
_t3_ok:

  /* Report the failure count in w0. */
  bn.mov w0, w3
  ecall

