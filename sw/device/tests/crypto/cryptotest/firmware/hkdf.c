status_t handle_hkdf(ujson_t *uj, hkdf_test_scratch_t *s) {
  // Declare test arguments
  cryptotest_hkdf_hash_alg_t uj_hash_alg;
  cryptotest_hkdf_input_t *uj_input = &s->input;
  // Deserialize test arguments from UART
  TRY(ujson_deserialize_cryptotest_hkdf_hash_alg_t(uj, &uj_hash_alg));
  TRY(ujson_deserialize_cryptotest_hkdf_input_t(uj, uj_input));

  otcrypto_key_mode_t key_mode;
  switch (uj_hash_alg) {
    case kCryptotestHkdfHashAlgSha256:
      key_mode = kOtcryptoKeyModeHmacSha256;
      break;
    case kCryptotestHkdfHashAlgSha384:
      key_mode = kOtcryptoKeyModeHmacSha384;
      break;
    case kCryptotestHkdfHashAlgSha512:
      key_mode = kOtcryptoKeyModeHmacSha512;
      break;
    default:
      LOG_ERROR("Unsupported HKDF hash algorithm: %d", uj_hash_alg);
      return INVALID_ARGUMENT();
  }
  if (uj_input->okm_len > HKDF_CMD_MAX_OKM_BYTES) {
    return INVALID_ARGUMENT();
  }
  // Build the key configurations
  otcrypto_key_config_t ikm_config = {
      .version = kOtcryptoLibVersion1,
      .key_mode = key_mode,
      .key_length = uj_input->ikm_len,
      .hw_backed = kHardenedBoolFalse,
      .security_level = kOtcryptoKeySecurityLevelPassiveRemote,
  };
  otcrypto_key_config_t okm_config = {
      .version = kOtcryptoLibVersion1,
      .key_mode = key_mode,
      .key_length = uj_input->okm_len,
      .hw_backed = kHardenedBoolFalse,
      .security_level = kOtcryptoKeySecurityLevelPassiveRemote,
  };
  // Create IKM shares.
  size_t ikm_words = ceil_div(uj_input->ikm_len, sizeof(uint32_t));
  memset(s->ikm_share0, 0, sizeof(s->ikm_share0));
  memcpy(s->ikm_share0, uj_input->ikm, uj_input->ikm_len);
  for (size_t i = 0; i < ikm_words; i++) {
    s->ikm_share0[i] ^= kTestMask[i];
  }
  otcrypto_const_word32_buf_t share0 = {
      .data = s->ikm_share0,
      .len = ikm_words,
  };
  otcrypto_const_word32_buf_t share1 = {
      .data = kTestMask,
      .len = ikm_words,
  };
  // Create blinded keys
  otcrypto_blinded_key_t ikm = {
      .config = ikm_config,
      .keyblob_length = 2 * ikm_words * sizeof(uint32_t),
      .keyblob = s->ikm_keyblob,
  };
  TRY(otcrypto_import_blinded_key(share0, share1, &ikm));
  size_t okm_words = ceil_div(uj_input->okm_len, sizeof(uint32_t));
  otcrypto_blinded_key_t okm = {
      .config = okm_config,
      .keyblob_length = 2 * okm_words * sizeof(uint32_t),
      .keyblob = s->okm_keyblob,
  };

  otcrypto_const_byte_buf_t salt = {
      .data = uj_input->salt,
      .len = uj_input->salt_len,
  };
  otcrypto_const_byte_buf_t info = {
      .data = uj_input->info,
      .len = uj_input->info_len,
  };
  otcrypto_status_t status = otcrypto_hkdf(&ikm, salt, info, &okm);
  if (status.value != kOtcryptoStatusValueOk) {
    return INTERNAL(status.value);
  }

  // Unmask the OKM
  uint32_t *okm_share0;
  uint32_t *okm_share1;
  TRY(keyblob_to_shares(&okm, &okm_share0, &okm_share1));
  uint32_t okm_buf[HKDF_CMD_MAX_OKM_BYTES / sizeof(uint32_t)];
  for (size_t i = 0; i < okm_words; i++) {
    okm_buf[i] = okm_share0[i] ^ okm_share1[i];
  }

  // Copy OKM to uJSON type
  cryptotest_hkdf_output_t uj_output;
  memcpy(uj_output.okm, okm_buf, uj_input->okm_len);
  uj_output.okm_len = uj_input->okm_len;

  // Send OKM to host via UART
  RESP_OK(ujson_serialize_cryptotest_hkdf_output_t, uj, &uj_output);
  return OK_STATUS(0);
}
