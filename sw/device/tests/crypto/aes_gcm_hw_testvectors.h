/**
 * @file
 * @brief AES-GCM test vectors for the AES-GCM hardware.
 *
 * All vectors have a 96-bit IV and a 128-bit tag, as the hardware supports.
 * They cover different sequences of GCM phases (full and partial blocks of AAD
 * and data, no AAD, no data) and all key lengths. Test cases 1-4, 10 and 16
 * are from "The Galois/Counter Mode of Operation (GCM)" by McGrew and Viega.
 */

enum {
  /** Maximum key length of the vectors in words (256 bits). */
  kAesGcmHwTestMaxKeyWords = 8,
  /** Maximum AAD length of the vectors in bytes. */
  kAesGcmHwTestMaxAadBytes = 20,
  /** Maximum data length of the vectors in bytes. */
  kAesGcmHwTestMaxDataBytes = 64,
};

/**
 * An AES-GCM test vector with a 96-bit IV and a 128-bit tag.
 */
typedef struct aes_gcm_hw_test_vector {
  /** Key length in 32-bit words. */
  size_t key_len;
  /** Key; words after `key_len` are unused. */
  uint32_t key[kAesGcmHwTestMaxKeyWords];
  /** IV. */
  uint32_t iv[kAesGcmHwIvNumWords];
  /** AAD length in bytes. */
  size_t aad_len;
  /** AAD. */
  uint8_t aad[kAesGcmHwTestMaxAadBytes];
  /** Plaintext and ciphertext length in bytes. */
  size_t data_len;
  /** Plaintext. */
  uint8_t plaintext[kAesGcmHwTestMaxDataBytes];
  /** Ciphertext. */
  uint8_t ciphertext[kAesGcmHwTestMaxDataBytes];
  /** Tag. */
  uint32_t tag[kAesGcmHwTagMaxNumWords];
} aes_gcm_hw_test_vector_t;

